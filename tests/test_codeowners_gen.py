def test_acceptance_item_3_renames_and_binary() -> None:
    log = (
        "\x1ecarol@x.io\n"
        "5\t0\tsrc/{old => new}/a.py\n"
        "2\t1\tsrc/{ => sub}/a.py\n"
        "4\t0\ta.txt => b.txt\n"
        "-\t-\tlogo.png\n"
    )
    commits = parse_log(log)
    assert len(commits) == 1
    files = commits[0].files
    assert files[0] == FileChange("src/new/a.py", 5, 0)
    assert files[1] == FileChange("src/sub/a.py", 2, 1)
    assert files[2] == FileChange("b.txt", 4, 0)
    assert files[3] == FileChange("logo.png", 1, 0)


def test_acceptance_item_4_author_handling_and_bots() -> None:
    log = "\x1eDev@x.io\n10\t0\tapp.py\n\x1ebuild[bot]@x.io\n50\t50\tapp.py\n"
    commits = parse_log(log)
    suggestion = suggest_owners(commits)
    # Author 'Dev@x.io' lowercased to 'dev@x.io'
    # build[bot]@x.io is excluded
    assert len(suggestion.rules) == 1
    assert suggestion.rules[0].pattern == "*"
    assert suggestion.rules[0].owners == ("dev@x.io",)


def test_acceptance_item_5_max_owners_and_tie_breaking() -> None:
    log = "\x1ebob@x.io\n10\t0\tsrc/b.py\n\x1ealice@x.io\n10\t0\tsrc/a.py\n"
    commits = parse_log(log)
    suggestion = suggest_owners(
        commits,
        handles={"bob@x.io": "@bob", "alice@x.io": "@alice"},
        max_owners=1,
    )
    # Bob and Alice both have weight 10 on src and total
    # Alice sorts before Bob
    src_rule = next(r for r in suggestion.rules if r.pattern == "/src/")
    assert src_rule.owners == ("@alice",)


def test_acceptance_item_6_skipped_directories() -> None:
    log = "\x1ealice@x.io\n5\t0\tmy docs/doc.md\n5\t0\t#hidden/secret.txt\n5\t0\tvalid/file.txt\n"
    commits = parse_log(log)
    suggestion = suggest_owners(commits, depth=1)
    assert "my docs/" in suggestion.skipped
    assert "#hidden/" in suggestion.skipped
    patterns = [r.pattern for r in suggestion.rules]
    assert "/my docs/" not in patterns
    assert "/#hidden/" not in patterns
    assert "/valid/" in patterns


def test_acceptance_item_7_errors() -> None:
    # Malformed line with 'x\ty\tz'
    with pytest.raises(CodeownersError) as exc_info:
        parse_log("\x1ealice@x.io\n1\t1\ta.py\nx\ty\tz\n")
    assert exc_info.value.code == "parse_error"
    assert "line 3" in str(exc_info.value)

    # Invalid handle
    with pytest.raises(CodeownersError) as exc_info:
        suggest_owners([], handles={"a@b.com": "@bad name"})
    assert exc_info.value.code == "invalid_handle"

    # Invalid options: depth=0 or min_share=1.5
    with pytest.raises(CodeownersError) as exc_info:
        suggest_owners([], depth=0)
    assert exc_info.value.code == "invalid_option"

    with pytest.raises(CodeownersError) as exc_info:
        suggest_owners([], min_share=1.5)
    assert exc_info.value.code == "invalid_option"

    with pytest.raises(CodeownersError) as exc_info:
        suggest_owners([], max_owners=0)
    assert exc_info.value.code == "invalid_option"

    with pytest.raises(CodeownersError) as exc_info:
        suggest_owners([], max_owners=11)
    assert exc_info.value.code == "invalid_option"

    # Input size limit: 10_000_001 bytes fails, 10_000_000 succeeds
    exact_max = "\x1ea@b.io\n" + "1\t1\ta.py\n" * ((10_000_000 - 10) // 9)
    # Pad to exactly 10_000_000
    pad = 10_000_000 - len(exact_max.encode("utf-8"))
    exact_max += "\n" * pad
    assert len(exact_max.encode("utf-8")) == 10_000_000
    parse_log(exact_max)

    with pytest.raises(CodeownersError) as exc_info:
        parse_log(exact_max + "x")
    assert exc_info.value.code == "input_too_large"


def test_acceptance_item_8_cli(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    history_path = tmp_path / "history.txt"
    history_path.write_text(
        "\x1ealice@x.io\n10\t2\tsrc/api/server.py\n\x1ebob@x.io\n5\t1\tsrc/api/client.py\n",
        encoding="utf-8",
    )
    handles_path = tmp_path / "map.json"
    handles_path.write_text(
        json.dumps({"alice@x.io": "@alice", "bob@x.io": "@bob"}), encoding="utf-8"
    )

    monkeypatch.chdir(tmp_path)
    exit_code = main(["history.txt", "--handles", "map.json", "--depth", "2"])
    captured = capsys.readouterr()
    assert exit_code == 0
    assert "/src/api/ @alice @bob" in captured.out

    # Missing file
    missing_exit = main(["non_existent_history.txt"])
    captured_err = capsys.readouterr()
    assert missing_exit == 2
    assert "error: cannot read non_existent_history.txt" in captured_err.err


