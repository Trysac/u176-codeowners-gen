"""Suggest a CODEOWNERS file from git log numstat output."""

from __future__ import annotations

import logging
import re
from collections import defaultdict
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Literal

__all__ = [
    "CodeownersError",
    "Commit",
    "FileChange",
    "Rule",
    "Suggestion",
    "__version__",
    "parse_log",
    "render",
    "suggest_owners",
]

__version__ = "0.1.0"

logger = logging.getLogger(__name__)
logger.addHandler(logging.NullHandler())

ErrorCode = Literal["input_too_large", "parse_error", "invalid_handle", "invalid_option"]

HASH_HEADER = "# Generated by codeowners-gen from git history. Review before committing."
HANDLE_RE = re.compile(r"^@[A-Za-z0-9-]+(/[A-Za-z0-9._-]+)?$")
EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+$")
RENAME_CURLY_RE = re.compile(r"^(.*?)\{(?:.*?)\s*=>\s*(.*?)\}(.*)$", re.DOTALL)
RENAME_SIMPLE_RE = re.compile(r"^(?:.*?)\s*=>\s*(.*?)$", re.DOTALL)


class CodeownersError(Exception):
    """Base error class for codeowners_gen."""

    def __init__(self, message: str, code: ErrorCode) -> None:
        truncated = message[:200] if len(message) > 200 else message
        super().__init__(truncated)
        self.code: ErrorCode = code


@dataclass(frozen=True)
class FileChange:
    """A change to a single file within a commit."""

    path: str
    added: int
    deleted: int


@dataclass(frozen=True)
class Commit:
    """A parsed git commit containing author email and file changes."""

    author: str
    files: tuple[FileChange, ...]


@dataclass(frozen=True)
class Rule:
    """A CODEOWNERS rule specifying a pattern and associated owners."""

    pattern: str
    owners: tuple[str, ...]


@dataclass(frozen=True)
class Suggestion:
    """The suggested CODEOWNERS rules and any directories skipped."""

    rules: tuple[Rule, ...]
    skipped: tuple[str, ...]


def _resolve_rename_path(raw_path: str) -> str:
    """Resolve git log rename syntax to the target new path."""
    curly_match = RENAME_CURLY_RE.match(raw_path)
    if curly_match:
        prefix, target, suffix = curly_match.groups()
        combined = f"{prefix}{target}{suffix}"
        while "//" in combined:
            combined = combined.replace("//", "/")
        return combined

    simple_match = RENAME_SIMPLE_RE.match(raw_path)
    if simple_match:
        target = simple_match.group(1)
        while "//" in target:
            target = target.replace("//", "/")
        return target

    return raw_path


def parse_log(text: str, *, max_bytes: int = 10_000_000) -> list[Commit]:
    """Parse git log output with record separator U+001E and numstat lines."""
    encoded_len = len(text.encode("utf-8"))
    if encoded_len > max_bytes:
        raise CodeownersError(
            f"Input size {encoded_len} exceeds limit of {max_bytes} bytes",
            code="input_too_large",
        )

    # Split commits by record separator U+001E
    # Track global line numbers for precise error reporting
    # Note: Use split('\n') instead of splitlines() to avoid issues with some platforms
    raw_lines = text.split("\n")
    current_author: str | None = None
    current_files: list[FileChange] = []
    commits: list[Commit] = []

    global_line_no = 0
    for raw_line in raw_lines:
        global_line_no += 1
        line = raw_line.rstrip("\r")
        if not line:
            continue
        if line.startswith("\x1e"):
            if current_author is not None:
                commits.append(Commit(author=current_author, files=tuple(current_files)))
                current_files = []
            author_candidate = line[1:].strip().lower()
            current_author = author_candidate
            continue

        if not line:
            continue

        if current_author is None:
            raise CodeownersError(
                f"Unexpected line before author header at line {global_line_no}: {line}",
                code="parse_error",
            )

        parts = line.split("\t")
        if len(parts) != 3:
            raise CodeownersError(
                f"Malformed numstat format at line {global_line_no}: {line}",
                code="parse_error",
            )

        added_str, deleted_str, raw_path = parts
        if added_str == "-" and deleted_str == "-":
            added = 1
            deleted = 0
        else:
            try:
                added = int(added_str)
                deleted = int(deleted_str)
            except ValueError as exc:
                raise CodeownersError(
                    f"Non-integer numstat numbers at line {global_line_no}: {line}",
                    code="parse_error",
                ) from exc

        resolved_path = _resolve_rename_path(raw_path)
        current_files.append(FileChange(path=resolved_path, added=added, deleted=deleted))

    if current_author is not None:
        commits.append(Commit(author=current_author, files=tuple(current_files)))

    return commits


def _validate_options(depth: int, min_share: float, max_owners: int) -> None:
    if depth < 1 or depth > 5:
        raise CodeownersError(f"depth must be between 1 and 5, got {depth}", code="invalid_option")
    if min_share <= 0.0 or min_share > 1.0:
        raise CodeownersError(
            f"min_share must be in (0, 1], got {min_share}", code="invalid_option"
        )
    if max_owners < 1 or max_owners > 10:
        raise CodeownersError(
            f"max_owners must be between 1 and 10, got {max_owners}", code="invalid_option"
        )


def _validate_handle(handle: str) -> None:
    if not (HANDLE_RE.match(handle) or EMAIL_RE.match(handle)):
        raise CodeownersError(
            f"Invalid handle '{handle}', must match GitHub handle or email format",
            code="invalid_handle",
        )


def suggest_owners(
    commits: Sequence[Commit],
    *,
    handles: Mapping[str, str] = {},
    depth: int = 1,
    min_share: float = 0.2,
    max_owners: int = 3,
    exclude: Sequence[str] = ("[bot]",),
) -> Suggestion:
    """Suggest CODEOWNERS rules based on git commit history."""
    _validate_options(depth=depth, min_share=min_share, max_owners=max_owners)

    validated_handles: dict[str, str] = {}
    for raw_email, raw_handle in handles.items():
        _validate_handle(raw_handle)
        validated_handles[raw_email.strip().lower()] = raw_handle

    root_weights: dict[str, int] = defaultdict(int)
    dir_weights: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    seen_dirs: set[str] = set()

    for commit in commits:
        author = commit.author.lower()
        if any(ex in author for ex in exclude):
            continue

        owner = validated_handles.get(author, author)

        for fc in commit.files:
            weight = fc.added + fc.deleted
            if weight <= 0:
                continue

            root_weights[owner] += weight

            # Extract directory path components up to depth
            path_parts = [p for p in fc.path.split("/") if p]
            if len(path_parts) > 1:
                dirs_count = min(len(path_parts) - 1, depth)
                subpath = "/".join(path_parts[:dirs_count])
                dir_pattern = f"/{subpath}/"
                seen_dirs.add(dir_pattern)
                dir_weights[dir_pattern][owner] += weight

    skipped: list[str] = []
    rules: list[Rule] = []

    # Compute root rule (*)
    total_root = sum(root_weights.values())
    if total_root > 0:
        eligible_root: list[tuple[str, int]] = []
        for owner, w in root_weights.items():
            share = w / total_root
            if share >= min_share:
                eligible_root.append((owner, w))
        # Sort descending by weight, then ascending by owner
        eligible_root.sort(key=lambda item: (-item[1], item[0]))
        selected = [owner for owner, _ in eligible_root[:max_owners]]
        if selected:
            rules.append(Rule(pattern="*", owners=tuple(selected)))

    # Directory rules
    # Dirs sorted ascending, deeper directories come after their parents
    sorted_dirs = sorted(seen_dirs)
    for dir_pattern in sorted_dirs:
        # Check skipping criteria: name contains space or starts with #
        # Stripping leading and trailing slashes for checking directory segment properties
        inner = dir_pattern[1:-1]
        if " " in inner or inner.startswith("#"):
            skipped.append(f"{inner}/")
            continue

        weights = dir_weights[dir_pattern]
        total_dir = sum(weights.values())
        if total_dir == 0:
            continue

        eligible_dir: list[tuple[str, int]] = []
        for owner, w in weights.items():
            share = w / total_dir
            if share >= min_share:
                eligible_dir.append((owner, w))
        eligible_dir.sort(key=lambda item: (-item[1], item[0]))
        selected = [owner for owner, _ in eligible_dir[:max_owners]]
        if selected:
            rules.append(Rule(pattern=dir_pattern, owners=tuple(selected)))

    return Suggestion(rules=tuple(rules), skipped=tuple(skipped))


def render(s: Suggestion) -> str:
    """Render Suggestion into CODEOWNERS file format."""
    lines = [HASH_HEADER]
    for rule in s.rules:
        owners_str = " ".join(rule.owners)
        lines.append(f"{rule.pattern} {owners_str}")
    return "\n".join(lines) + "\n"
